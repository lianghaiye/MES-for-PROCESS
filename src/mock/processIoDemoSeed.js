function stamp(daysAgo = 0, time = '09:30:00') {
  const d = dayjs().subtract(daysAgo, 'day')
  return {
    date: d.format('YYYY-MM-DD'),
    at: `${d.format('YYYY-MM-DD')} ${time}`,
  }
}

