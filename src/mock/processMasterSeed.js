/**
 * 流程型主数据：涂料配方相关的产品与物料。
 * id 与配方目录 PROCESS_ITEMS 对齐，便于投料和产出直接引用。
 */

function packRows(id, rows) {
  return rows.map((row, index) => ({
    id: `${id}-pack-${index + 1}`,
    name: row.name,
    packUnit: row.unit || '',
    qty: row.qty ?? null,
    isBulk: Boolean(row.bulk),
    isDefault: index === 0,
    enabled: true,
    salesPrice: row.salesPrice ?? null,
    purchasePrice: row.purchasePrice ?? null,
    remark: row.remark || '',
  }))
}

function alertOf({ min, max, expiry = true, days = 30, defect = 2 }) {
  return {
    stockAlertEnabled: true,
    maxStockQty: max,
    minStockQty: min,
    expiryAlertEnabled: expiry,
    expiryAlertDays: expiry ? days : null,
    defectRateThreshold: defect,
    attachments: [],
  }
}

function withVolumeAux(row) {
  const density = Number(row.density)
  const base = row.inventoryUnit
  const mass = base === 'kg' || base === '公斤' || base === '千克'
  if (!(density > 0) || !mass) return row
  return {
    ...row,
    purchaseUnit: '升',
    packageContent: density,
    auxUnits: [
      {
        id: `aux-${row.id}-l`,
        unit: '升',
        convertType: 'fixed',
        rate: density,
        allowDecimal: true,
        roles: ['purchase'],
        enabled: true,
      },
    ],
  }
}

function supplier(name, price, days) {
  return {
    id: `ps-${name}`,
    supplierName: name,
    supplierType: '采购',
    unitPriceExTax: price,
    currency: 'CNY',
    leadTimeDays: days,
  }
}

